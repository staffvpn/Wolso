import type { Env } from '../types';

/** Ничего не ограничивало частоту запросов вообще: один скрипт мог налить
 *  тысячу откликов, сообщений или вакансий, и вместе с каждым улетало
 *  сообщение в бота — то есть спамили бы не только базу, но и живых людей.
 *
 *  Счёт идёт по строкам, которые действие и так создаёт (отклики,
 *  сообщения, смены), а не по отдельной таблице счётчиков: лишней записи
 *  на каждый запрос не появляется, лимит переживает перезапуск воркера, и
 *  нет ещё одного места, которое надо чистить. Взамен окно скользящее и
 *  считается запросом — на порядок дешевле, чем то, что за ним следует
 *  (вставка плюс вызов Telegram). */
export interface RateLimit {
  /** Сколько таких действий разрешено в окне. */
  max: number;
  /** Окно, в формате модификатора SQLite: '-1 hour', '-10 minutes'. */
  window: string;
}

/** Отклики: человек физически не может выйти на 30 смен в сутки, так что
 *  всё, что выше, — либо перебор наугад, либо скрипт. */
export const APPLY_LIMIT: RateLimit = { max: 30, window: '-1 day' };

/** Сообщения — на чат, а не на аккаунт: в таблице messages нет автора,
 *  только chat_id и сторона. Флуд в одну переписку это останавливает; на
 *  флуд во все сразу косвенно работает лимит откликов выше — чатов у
 *  человека ровно столько, сколько приглашений и откликов. */
export const MESSAGE_LIMIT: RateLimit = { max: 60, window: '-1 hour' };

/** Публикация смен: у заведения их не бывает по двадцать в час. */
export const VACANCY_LIMIT: RateLimit = { max: 20, window: '-1 hour' };

/** Возвращает true, если лимит уже выбран. Ошибку не бросает: свалившийся
 *  счётчик не должен ронять действие, ради которого пришёл человек. */
export async function overLimit(
  env: Env,
  table: 'applications' | 'messages' | 'shifts',
  column: string,
  id: number | string,
  limit: RateLimit,
): Promise<boolean> {
  try {
    const row = await env.DB.prepare(
      `SELECT COUNT(*) as n FROM ${table} WHERE ${column} = ? AND created_at >= datetime('now', ?)`,
    )
      .bind(id, limit.window)
      .first<{ n: number }>();
    return (row?.n ?? 0) >= limit.max;
  } catch {
    return false;
  }
}
