-- Статус личной смены и то, где человек её нашёл.
--
-- Раньше статус выводился из даты: прошла — значит отработана. На бумаге
-- это выглядело честно, на практике — нет. Смену заносят заранее, потом
-- она срывается, переносится или человек просто не выходит, а календарь
-- всё равно записывает её в отработанные и в заработок за месяц. Отметить
-- «запланировал» было нечем — этого и не хватало. Статус теперь ставит
-- сам человек, датой он только предзаполняется при создании.
--
-- 'planned' по умолчанию: новая запись — это план, пока не сказано иначе.
ALTER TABLE personal_shifts ADD COLUMN status TEXT NOT NULL DEFAULT 'planned';

-- Где нашёл работу: телеграм-канал, Авито, hh.ru и прочее. Свободный текст
-- (пустая строка = не указано), а не справочник: список площадок меняется
-- чаще, чем схема, и заводить ради него таблицу с ключами не за чем. В
-- приложении это выбор из готовых вариантов, но сервер лишнего не
-- запрещает.
ALTER TABLE personal_shifts ADD COLUMN found_via TEXT NOT NULL DEFAULT '';

-- Уже занесённые смены не должны разом стать «запланированными»: до этой
-- миграции прошедшая дата и означала «отработана», и человек видел их
-- именно так. Переносим ровно то, что показывалось.
UPDATE personal_shifts SET status = 'worked' WHERE date < date('now');
