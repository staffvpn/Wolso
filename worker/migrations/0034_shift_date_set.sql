-- Разовая смена на произвольные дни: 13-е и 27-е, а не только «13-е» или
-- «13–15».
--
-- До сих пор вакансия описывалась парой date + end_date, то есть только
-- сплошным отрезком. Работодателю, которому человек нужен два раза в
-- месяц, оставалось публиковать две вакансии и потом собирать одного и
-- того же человека из двух разных наборов откликов.
--
-- Почему добавляем список, а не таблицу дней. date и end_date остаются
-- границами и по-прежнему участвуют во всех запросах — ленте, сортировке,
-- закрытии смены, дашборде, выгрузках. Ни один из них трогать не нужно:
-- date — первый день, end_date — последний, как и было. dates только
-- уточняет, какие дни внутри этих границ реально нужны. Отдельная таблица
-- потребовала бы join в каждом из этих мест ради того же самого.
--
-- Пустая строка = «все дни подряд от date до end_date», то есть ровно то
-- поведение, которое было до этой миграции. Поэтому старые строки менять
-- не надо, и код, не знающий про столбец, продолжает читать их правильно.
ALTER TABLE shifts ADD COLUMN dates TEXT NOT NULL DEFAULT '';
