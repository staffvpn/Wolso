-- Что человек ищет: смены, постоянную работу или и то и другое. Раньше это
-- знал только сам соискатель — работодатель звал на постоянку человека,
-- которому нужна была подработка на выходные, и выяснялось это уже в чате.
--
-- 'any' (по умолчанию) — согласен и на то, и на другое: так ведут себя все
-- существующие анкеты, и это честнее, чем угадать за них.
ALTER TABLE workers ADD COLUMN looking_for TEXT NOT NULL DEFAULT 'any';

-- Регистрация подставляла каждому новому соискателю строку опыта
-- «Бариста · 0 месяцев». Она считалась заполненным опытом (проверка была
-- «есть хоть одна строка»), так что анкету можно было пройти, не указав
-- ничего, и в анкете у людей висело «0 месяцев» — из-за чего форма опыта и
-- выглядела непонятной. Теперь опыт добавляется только руками, а нулевые
-- строки — не опыт: удаляем их и требуем реальный срок.
DELETE FROM worker_positions WHERE months = 0;
