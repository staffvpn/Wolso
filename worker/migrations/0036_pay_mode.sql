-- Как работодатель называет оплату: ставкой в час или суммой за смену.
--
-- До сих пор в форме была только ставка, а сумма за выход считалась из неё
-- и часов. Договариваются же чаще наоборот — «три тысячи за смену», — и
-- работодателю приходилось делить в уме, чтобы вписать ставку, из которой
-- потом получалась не та сумма, о которой он думал: 3000 за 9 часов это
-- 333.33, а вписать можно только целое.
--
-- Колонки под сумму заводить не нужно: hourly_rate и total_pay уже есть и
-- по-прежнему заполняются обе, что бы работодатель ни выбрал. Меняется
-- только то, какая из них введена, а какая посчитана, — и это ровно то,
-- что здесь хранится. Так фильтр ленты по ставке, статистика и выгрузки
-- продолжают работать не глядя на режим.
--
-- 'hourly' по умолчанию: все опубликованные до сих пор смены именно такие.
ALTER TABLE shifts ADD COLUMN pay_mode TEXT NOT NULL DEFAULT 'hourly';
