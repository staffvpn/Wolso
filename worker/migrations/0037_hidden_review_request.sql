-- Когда человек со скрытой анкетой её правит, оператору уходит одно
-- сообщение: «исправил, посмотрите ещё раз». Правок за один заход бывает
-- много — имя, фото, опыт сохраняются по отдельности, — поэтому нужна
-- отметка о последнем таком сообщении, иначе оператор получит десяток
-- одинаковых подряд.
--
-- Сбрасывается в NULL при каждой смене видимости анкеты: после возврата
-- в поиск и повторного скрытия цикл должен начинаться заново.
ALTER TABLE workers ADD COLUMN hidden_edit_notified_at TEXT;
