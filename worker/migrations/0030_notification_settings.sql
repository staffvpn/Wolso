-- Переключатели уведомлений в «Настройках» были декорацией: они лежали
-- только в localStorage телефона, их не читал никто, кроме самого экрана
-- настроек, и до сервера они не доезжали вообще. Бот слал всё подряд
-- независимо от того, что человек выключил, — а выключал он это ровно
-- потому, что хотел, чтобы перестало приходить.
--
-- По умолчанию всё включено: так система вела себя до сих пор, и молча
-- отписать всех при накатывании миграции было бы хуже, чем ничего не
-- делать.
ALTER TABLE workers ADD COLUMN notify_new_shifts INTEGER NOT NULL DEFAULT 1;
ALTER TABLE workers ADD COLUMN notify_employer_replies INTEGER NOT NULL DEFAULT 1;
ALTER TABLE workers ADD COLUMN notify_shift_reminder INTEGER NOT NULL DEFAULT 1;

-- Напоминание перед сменой раньше не отправлялось ничем — переключатель
-- управлял функцией, которой не существовало. Теперь его шлёт крон, и здесь
-- отмечается, кому уже напомнили: без этого ежечасный запуск напоминал бы
-- об одной смене каждый час до её начала.
ALTER TABLE applications ADD COLUMN shift_reminded_at TEXT;
