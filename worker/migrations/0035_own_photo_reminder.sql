-- Отметка о напоминании «поставьте своё фото».
--
-- При регистрации Wolso копирует картинку из Telegram, и формально фото
-- есть у всех — только у половины это машина, кот или пейзаж. Работодатель
-- в ленте кандидатов выбирает по лицу, так что анкета с чужой картинкой
-- проигрывает, а человек об этом не знает.
--
-- Столбец нужен ровно затем же, зачем signup_reminded_at в 0028: чтобы
-- напоминание ушло один раз, а не каждый час, когда крон снова увидит ту
-- же анкету. Пишется сразу после отправки, независимо от того, дошло ли
-- сообщение: у заблокировавшего бота оно не дойдёт никогда, а цикл должен
-- заканчиваться.
ALTER TABLE workers ADD COLUMN photo_reminded_at TEXT;
