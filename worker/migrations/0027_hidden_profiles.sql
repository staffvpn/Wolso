-- пользоваться приложением; у скрытого всё работает, он просто не участвует
-- в подборе: не появляется в «Найти сотрудников» у работодателей и не может
-- откликаться на новые смены. Уже начатое — отклики, приглашения, чаты,
-- подтверждённые смены — не трогается, человек доигрывает то, что начал.
--
-- Причина не обязательна (в отличие от блокировки), но если её написали,
-- человек увидит её у себя в профиле — чтобы не гадать, почему его перестали
-- звать, и не идти в поддержку с «у меня ничего не работает».
