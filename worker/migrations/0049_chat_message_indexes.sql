-- Чат-лист (GET /chats) ищет «последнее сообщение» и «сколько непрочитано»
-- на каждый чат в списке — раньше без этого индекса SQLite находил
-- последнее сообщение, перебирая всю историю чата по chat_id (уже был
-- индекс на сам chat_id, но не на порядок внутри него). При опросе списка
-- каждые несколько секунд с длинной историей переписки это съедало
-- огромную часть дневного лимита D1 на чтения.
CREATE INDEX idx_messages_chat_created ON messages(chat_id, created_at);

-- Отдельно — для подсчёта непрочитанных (read = 0), той же логики ради.
CREATE INDEX idx_messages_chat_read ON messages(chat_id, read);
